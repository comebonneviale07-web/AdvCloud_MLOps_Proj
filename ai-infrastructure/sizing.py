"""Resource sizing report (step 2) + theoretical training-memory table (step 5).

    python ai-infrastructure/sizing.py --bundle artifacts/bundle

Reads measured values from the bundle's meta.json (written by trajclf.train:
training time, peak memory, hardware, parameter count, file sizes) and the
processed dataset, then writes ai-infrastructure/resource-sizing.md.
Measured and calculated values are kept in separate tables.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent


def training_state_bytes(n_params: int, n_gpus: int = 1) -> dict:
    """Idealised model-state memory per GPU, fp32 + Adam (TP3 formulas).

    weights 4 B + grads 4 B + Adam m,v 8 B = 16 B/param (activations excluded).
    """
    weights, grads, adam = 4 * n_params, 4 * n_params, 8 * n_params
    return {
        "DDP (replicated)": weights + grads + adam,
        "ZeRO-1 (shard optimizer)": weights + grads + adam / n_gpus,
        "ZeRO-2 (+ shard grads)": weights + (grads + adam) / n_gpus,
        "ZeRO-3 / FSDP (+ shard params)": (weights + grads + adam) / n_gpus,
    }


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--bundle", default=str(REPO / "artifacts/bundle"))
    p.add_argument("--splits", default=str(REPO / "data/processed/splits.npz"))
    p.add_argument("--raw-dir", default=str(REPO / "data/raw"))
    p.add_argument("--n-gpus", type=int, default=2)
    args = p.parse_args()

    meta = json.loads((Path(args.bundle) / "meta.json").read_text())
    params = meta.get("params", {})
    n_params = int(params.get("model.n_parameters", 0))
    splits = np.load(args.splits)
    raw = {f.name: f.stat().st_size / 1e6 for f in Path(args.raw_dir).glob("*") if f.is_file()}
    processed_mb = sum(splits[k].nbytes for k in splits.files) / 1e6
    hw = meta.get("hardware", {})

    lines = ["# Resource sizing (generated by `ai-infrastructure/sizing.py`)", "",
             "## Measured / observed", "", "| Item | Value | Source |", "|---|---|---|"]
    for name, mb in sorted(raw.items()):
        lines.append(f"| Raw file `{name}` | {mb:.1f} MB | file system |")
    lines += [
        f"| Labelled rides (train / val / test) | {len(splits['y_train'])} / {len(splits['y_val'])} / "
        f"{len(splits['y_test'])} | processed splits |",
        f"| Model input shape | {params.get('data.input_shape', '?')} per ride | preprocess.json |",
        f"| Processed tensors in RAM | {processed_mb:.1f} MB | splits.npz (float32) |",
        f"| Parameters | {n_params:,} | `model.n_parameters` |",
    ]
    for f, mb in meta.get("file_size_mb", {}).items():
        lines.append(f"| Serialized `{f}` | {mb:.3f} MB | bundle |")
    lines += [
        f"| Hardware | {hw.get('gpu', hw.get('cpu', '?'))}, {hw.get('ram_gb', '?')} GB RAM"
        f"{', ' + str(hw.get('vram_gb')) + ' GB VRAM' if hw.get('vram_gb') else ''} | train.py |",
        f"| Batch size / epochs | {params.get('train.batch_size')} / {params.get('train.epochs')} | config |",
        f"| Training time | {meta.get('training_time_s', '?')} s | train.py (wall clock) |",
        f"| Peak GPU memory (allocated) | {meta.get('peak_gpu_mem_mb', 0)} MB | torch.cuda.max_memory_allocated |",
        f"| Peak process RSS | {meta.get('peak_rss_mb', '?')} MB | psutil |",
        "", f"## Calculated (theoretical, NOT measured) — model states, {args.n_gpus} GPUs", "",
        "| Strategy | Per-GPU model-state memory |", "|---|---|",
    ]
    for k, v in training_state_bytes(n_params, args.n_gpus).items():
        lines.append(f"| {k} | {v / 1e6:.3f} MB |")
    lines += ["", "Formula: 16 bytes/parameter (fp32 weights + grads + Adam m, v); activations excluded.", ""]
    out = ROOT / "resource-sizing.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nwritten to {out}")


if __name__ == "__main__":
    main()
